#!/usr/bin/env python3
"""Deterministic fixture generator for the cadquery STEP quantity adapter.

Writes tests/fixtures/bracket-solid.step — an L-bracket with two through-holes
whose volume / surface area / bounding box have exact hand-derived closed forms
(see ANALYTIC below). The committed fixture is authoritative for the bun tests
(src/engines/adapters/quantities.test.ts); regenerating under the pinned venv
(cadquery 2.6.1 / OCCT 7.8) reproduces byte-identical output — the OCC-written
header (which embeds a wall-clock timestamp) is normalized to a fixed literal.

Geometry (all millimetres, profile in the XY plane, extruded +Z):
  - foot: X 0..80, Y 0..10
  - leg : X 0..10, Y 0..50
  - extrusion depth: 30
  - two Ø8 through-holes (r = 4), axis Z, centres (30, 5) and (60, 5)

ANALYTIC (hand-derived, independent of OCC/cadquery):
  profile area      A = 80*10 + 10*50 - 10*10        = 1200 mm2
  volume            V = A*30 - 2*(pi*4^2*30)        = 36000 - 960*pi  ~  32984.0711 mm3
  profile perimeter P = 2*(80+50)                    = 260 mm  (an L notch removes one
                     horizontal run and adds one equal horizontal run, likewise vertically)
  surface area      S = 2*(A - 2*pi*4^2) + P*30 + 2*(2*pi*4*30)
                                                    = 10200 + 416*pi  ~  11506.9025 mm2
  bounding box      80 x 50 x 30  ->  diagonal sqrt(80^2+50^2+30^2) = sqrt(9800) ~ 98.9949 mm

The generator self-checks the exported file by re-importing it and comparing the
engine-computed values against these closed forms (rel. tol 1e-9); exit 1 on any
mismatch. Run: /home/z/.venv/bin/python3 make_fixture_bracket.py
"""

import hashlib
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURE_DIR = os.path.normpath(os.path.join(HERE, "..", "..", "..", "tests", "fixtures"))
OUT_PATH = os.path.join(FIXTURE_DIR, "bracket-solid.step")

# Fixture parameters (mm) — mirror of the ANALYTIC block above.
FOOT_X, FOOT_Y = 80.0, 10.0   # foot rectangle: X 0..80, Y 0..10
LEG_X, LEG_Y = 10.0, 50.0     # leg rectangle : X 0..10, Y 0..50
DEPTH = 30.0                  # extrusion in +Z
HOLE_R = 4.0                  # through-hole radius
HOLE_CENTRES = [(30.0, 5.0), (60.0, 5.0)]  # axis Z, mid-foot

EXPECTED_VOLUME = (FOOT_X * FOOT_Y + LEG_X * LEG_Y - LEG_X * FOOT_Y) * DEPTH \
    - len(HOLE_CENTRES) * math.pi * HOLE_R**2 * DEPTH
EXPECTED_AREA = 2.0 * ((FOOT_X * FOOT_Y + LEG_X * LEG_Y - LEG_X * FOOT_Y)
                       - len(HOLE_CENTRES) * math.pi * HOLE_R**2) \
    + 2.0 * (FOOT_X + LEG_Y) * DEPTH \
    + len(HOLE_CENTRES) * 2.0 * math.pi * HOLE_R * DEPTH
EXPECTED_BBOX_DIAG = math.sqrt(FOOT_X**2 + LEG_Y**2 + DEPTH**2)


def fail(msg: str) -> None:
    print(f"FAIL: {msg}", file=sys.stderr)
    sys.exit(1)


def build_and_export() -> None:
    import cadquery as cq
    from cadquery import exporters

    profile_pts = [
        (0.0, 0.0),
        (FOOT_X, 0.0),
        (FOOT_X, FOOT_Y),
        (LEG_X, FOOT_Y),
        (LEG_X, LEG_Y),
        (0.0, LEG_Y),
    ]
    solid = cq.Workplane("XY").polyline(profile_pts).close().extrude(DEPTH)
    holes = cq.Workplane("XY").pushPoints(HOLE_CENTRES).circle(HOLE_R).extrude(DEPTH)
    bracket = solid.cut(holes)
    solids = bracket.solids().vals()
    if len(solids) != 1:
        fail(f"expected exactly 1 solid after boolean cut, got {len(solids)} "
             "(hole/edge tangency can fragment the solid — fixture parameters are wrong)")

    exporters.export(bracket, OUT_PATH, exporters.ExportTypes.STEP)

    # Normalize the OCC header: fixed timestamp + honest origin description so
    # regeneration is byte-identical and the fixture documents its own source.
    with open(OUT_PATH, "r", encoding="utf-8") as f:
        text = f.read()
    text = re.sub(
        r"FILE_DESCRIPTION\(.*?\);",
        "FILE_DESCRIPTION(('Engineering OS W2-b quantity fixture - L-bracket "
        "generated by src/engines/adapters/make_fixture_bracket.py'),'2;1');",
        text, count=1, flags=re.S,
    )
    text = re.sub(
        r"FILE_NAME\([^;]*\);",
        "FILE_NAME('bracket-solid.step','2026-01-01T00:00:00',('Engineering OS'),"
        "('Engineering OS'),'Manual','');",
        text, count=1,
    )
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write(text)


def self_check() -> None:
    from cadquery import importers

    wp = importers.importStep(OUT_PATH)
    solids = wp.solids().vals()
    if len(solids) != 1:
        fail(f"re-import: expected 1 solid, got {len(solids)}")
    solid = solids[0]
    volume = float(solid.Volume())
    area = float(solid.Area())
    bbox = solid.BoundingBox()
    diag = math.sqrt(bbox.xlen**2 + bbox.ylen**2 + bbox.zlen**2)

    for name, measured, expected in (
        ("volume", volume, EXPECTED_VOLUME),
        ("area", area, EXPECTED_AREA),
        ("bbox diagonal", diag, EXPECTED_BBOX_DIAG),
    ):
        rel = abs(measured - expected) / expected
        if rel > 1e-9:
            fail(f"self-check {name}: measured {measured!r} vs analytic {expected!r} (rel {rel:.3e})")
        print(f"self-check {name}: engine={measured:.9f} analytic={expected:.9f} (rel {rel:.2e})")


def main() -> None:
    build_and_export()
    self_check()
    with open(OUT_PATH, "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    print(f"wrote {OUT_PATH}")
    print(f"sha256 {digest}")
    print(f"analytic volume = 36000 - 960*pi = {EXPECTED_VOLUME:.9f} mm^3")
    print(f"analytic area   = 10200 + 416*pi = {EXPECTED_AREA:.9f} mm^2")
    print(f"analytic bbox diag = sqrt(9800)  = {EXPECTED_BBOX_DIAG:.9f} mm")


if __name__ == "__main__":
    main()
