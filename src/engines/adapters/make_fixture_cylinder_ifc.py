#!/usr/bin/env python3
"""Deterministic fixture generator for the IfcOpenShell quantity adapter.

Writes tests/fixtures/cylinder-geometry.ifc — an IFC4 cylindrical column
(IfcColumn, r = 0.2 m, h = 3.0 m; a Ø400 x 3000 mm concrete column) with a
SweptSolid body and NO declared IfcElementQuantity. This forces the adapter's
GEOMETRIC FALLBACK path: the PyPI ifcopenshell wheel has no OCCT geometry
backend (ifcopenshell.geom.has_occ == False), so quantities come from mesh
triangulation (divergence-theorem volume + triangle-sum area) — an APPROXIMATION
for curved surfaces. The validation harness runs this case at the pinned 1%
"mesh" tolerance and records the observed relative error: this quantifies the
wheel limitation honestly instead of hiding it.

Byte-deterministic plain-text SPF: fixed GlobalId + fixed header timestamp, so
regenerating reproduces identical bytes (sha256-stable).

ANALYTIC (hand-derived, independent of ifcopenshell):
  volume V = pi * 0.2^2 * 3.0             = 0.12*pi  ~ 0.3769911184 m3
  surface S = 2*pi*0.2*3.0 + 2*pi*0.2^2   = 1.28*pi  ~ 4.0212385966 m2
            (lateral 1.2*pi + two caps 0.08*pi)

Self-check (requires ifcopenshell, same venv as the adapter): re-opens the file,
verifies there is NO IfcElementQuantity anywhere (so the fallback path is
genuinely exercised), verifies the mesh path with the wheel's DEFAULT settings
(the same settings object the production adapter constructs) reproduces within
1% of the closed forms — the pinned mesh tolerance — and prints the observed
relative errors (the same numbers the harness records in its report).
Run: /home/z/.venv/bin/python3 make_fixture_cylinder_ifc.py
"""

import hashlib
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURE_DIR = os.path.normpath(os.path.join(HERE, "..", "..", "..", "tests", "fixtures"))
OUT_PATH = os.path.join(FIXTURE_DIR, "cylinder-geometry.ifc")

# Fixture parameters (m) — mirror of the ANALYTIC block above.
COL_R, COL_H = 0.2, 3.0
COL_GUID = "4rUnE8CnPHBwLdZzIqZkf1"

EXPECTED_VOLUME = math.pi * COL_R**2 * COL_H
EXPECTED_AREA = 2.0 * math.pi * COL_R * COL_H + 2.0 * math.pi * COL_R**2

# Pinned mesh tolerance from the corpus contract (harness uses the same bound):
# 1% engineering tolerance for triangulated curved-surface quantities.
MESH_REL_TOL = 0.01

FILE_TEXT = f"""ISO-10303-21;
HEADER;
FILE_DESCRIPTION(('Engineering OS W2-c quantity fixture - generated by src/engines/adapters/make_fixture_cylinder_ifc.py'),'2;1');
FILE_NAME('cylinder-geometry.ifc','2026-01-01T00:00:00',('Engineering OS'),('Engineering OS'),'Manual','');
FILE_SCHEMA(('IFC4'));
ENDSEC;
DATA;
#1=IFCPROJECT('6rUnE8CnPHBwLdZzIqZkf0',$,'Cylinder Fixture',$,$,$,$,(#2),#8);
#2=IFCGEOMETRICREPRESENTATIONCONTEXT($,'Model',3,1.E-05,#3,$);
#3=IFCAXIS2PLACEMENT3D(#4,$,$);
#4=IFCCARTESIANPOINT((0.,0.,0.));
#5=IFCSIUNIT(*,.LENGTHUNIT.,$,.METRE.);
#6=IFCSIUNIT(*,.AREAUNIT.,$,.SQUARE_METRE.);
#7=IFCSIUNIT(*,.VOLUMEUNIT.,$,.CUBIC_METRE.);
#8=IFCUNITASSIGNMENT((#5,#6,#7));
#9=IFCLOCALPLACEMENT($,#3);
#10=IFCCOLUMN('{COL_GUID}',$,'Mesh Column',$,$,#9,#11,$,$);
#11=IFCPRODUCTDEFINITIONSHAPE($,$,(#12));
#12=IFCSHAPEREPRESENTATION(#2,'Body','SweptSolid',(#13));
#13=IFCEXTRUDEDAREASOLID(#14,#3,#17,{COL_H:.1f});
#14=IFCCIRCLEPROFILEDEF(.AREA.,$,#15,{COL_R:.1f});
#15=IFCAXIS2PLACEMENT2D(#16,$);
#16=IFCCARTESIANPOINT((0.,0.));
#17=IFCDIRECTION((0.,0.,1.));
ENDSEC;
END-ISO-10303-21;
"""


def fail(msg: str) -> None:
    print(f"FAIL: {msg}", file=sys.stderr)
    sys.exit(1)


def mesh_volume_area(verts, faces):
    """Divergence-theorem volume + triangle-sum area (mirrors the adapter)."""
    vol = 0.0
    area = 0.0
    for i in range(0, len(faces), 3):
        a, b, c = faces[i], faces[i + 1], faces[i + 2]
        p0 = verts[a * 3:a * 3 + 3]
        p1 = verts[b * 3:b * 3 + 3]
        p2 = verts[c * 3:c * 3 + 3]
        ux, uy, uz = p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]
        vx, vy, vz = p2[0] - p0[0], p2[1] - p0[1], p2[2] - p0[2]
        cx, cy, cz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
        area += math.sqrt(cx * cx + cy * cy + cz * cz) / 2.0
        vol += (p0[0] * (p1[1] * p2[2] - p1[2] * p2[1])
                - p0[1] * (p1[0] * p2[2] - p1[2] * p2[0])
                + p0[2] * (p1[0] * p2[1] - p1[1] * p2[0])) / 6.0
    return abs(vol), area


def generate() -> None:
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(FILE_TEXT)


def self_check() -> None:
    try:
        import ifcopenshell
        import ifcopenshell.geom
    except Exception as e:
        print(f"self-check SKIPPED (ifcopenshell not importable: {e}) — file still written")
        return

    f = ifcopenshell.open(OUT_PATH)
    cols = f.by_type("IfcColumn")
    if len(cols) != 1:
        fail(f"expected 1 IfcColumn, got {len(cols)}")
    if f.by_type("IfcElementQuantity"):
        fail("fixture must NOT contain any IfcElementQuantity — it exists to exercise "
             "the geometric (mesh) fallback, not the declared-quantity path")
    if cols[0].GlobalId != COL_GUID:
        fail(f"GlobalId mismatch: {cols[0].GlobalId!r} != {COL_GUID!r}")

    # The production adapter builds ifcopenshell.geom.settings() with DEFAULT
    # values — mirror that exactly (no custom deflection): whatever the default
    # triangulation gives is the honest number the harness must record.
    shape = ifcopenshell.geom.create_shape(ifcopenshell.geom.settings(), cols[0])
    verts = list(shape.geometry.verts)
    faces = list(shape.geometry.faces)
    vol, area = mesh_volume_area(verts, faces)
    print(f"default-settings triangulation: verts={len(verts) // 3} tris={len(faces) // 3}")
    for name, measured, expected in (("volume", vol, EXPECTED_VOLUME),
                                     ("surface area", area, EXPECTED_AREA)):
        rel = abs(measured - expected) / expected
        print(f"mesh fallback {name}: engine={measured!r} analytic={expected!r} (rel {rel:.4e})")
        if rel > MESH_REL_TOL:
            fail(f"mesh {name} rel error {rel:.4e} EXCEEDS the pinned 1% mesh tolerance — "
                 "this is a REAL finding: record it honestly in the harness report; "
                 "do NOT loosen the tolerance")
    # determinism smoke check (the harness does the full bitwise double-run)
    shape2 = ifcopenshell.geom.create_shape(ifcopenshell.geom.settings(), cols[0])
    if list(shape2.geometry.verts) != verts or list(shape2.geometry.faces) != faces:
        fail("default-settings triangulation is not deterministic between two runs")


def main() -> None:
    generate()
    self_check()
    with open(OUT_PATH, "rb") as fh:
        print(f"wrote {OUT_PATH}")
        print(f"sha256 {hashlib.sha256(fh.read()).hexdigest()}")
    print(f"analytic: V = 0.12*pi = {EXPECTED_VOLUME!r} m3, S = 1.28*pi = {EXPECTED_AREA!r} m2")


if __name__ == "__main__":
    main()
